import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseFit} from '../js/fit.js';
import {RideStats, METRICS,formatValue,formatTime} from '../js/metrics.js';
const b=readFileSync(new URL('../examples/DEMO_SYNTHETIC.fit',import.meta.url));
const buffer=b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength);
const fit=parseFit(buffer);
assert.ok(fit.records.length>10,'FIT records');
assert.equal(Object.keys(METRICS).length,18,'18 metrics');
const stats=new RideStats(fit);
const early=stats.at(Math.min(6,fit.duration),0),late=stats.at(fit.duration,0);
assert.ok(Number.isFinite(late.total_distance));
assert.ok(late.max_speed>=early.max_speed);
assert.ok(late.max_cadence>=early.max_cadence);
assert.ok(late.max_heart_rate>=early.max_heart_rate);
assert.ok(late.avg_power>=0);
assert.ok(late.segment_distance>=0);
assert.equal(late.segment_distance,late.total_distance);
assert.equal(stats.at(fit.duration,fit.duration).segment_distance,0);
assert.ok(late.np===null||Number.isFinite(late.np));
assert.equal(formatTime(3661),'01:01:01');
assert.equal(formatValue('power3',null),'—');
console.log('PASS: FIT parsed',fit.samples,'records, duration',fit.duration);
console.log('PASS: 18 metrics, cumulative max/avg, NP, segment distance, format');
console.log('last frame:',late);
